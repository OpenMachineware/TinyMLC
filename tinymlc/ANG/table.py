# table.py
# Table-driven network generation.
#
# The table contains pre-computed optimal network structures for
# different hardware constraints. This allows instant lookup without
# running the generate algorithm.
#
# Table operations:
#   - build_table: Generate a table from scratch
#   - lookup: Find the best network for given constraints
#   - update_table: Add new entries or recalibrate existing ones
#   - merge: Combine two tables
#   - prune: Remove stale entries
#   - get_stats: Get table statistics


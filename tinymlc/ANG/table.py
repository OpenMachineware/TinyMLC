    def merge(self, other_table_path: str) -> None:
        """
        Merge another table into this one.

        Args:
            other_table_path: Path to the other table file.
        """
        other = TableManager(other_table_path)

        for entry in other.entries:
            signature = entry.get("signature", "")
            if signature in self._index:
                # Entry exists, skip (keep existing)
                continue
            # Add new entry
            self.entries.append(entry)

        self._rebuild_index()
        self.metadata["merged_at"] = time.time()

    def prune(
        self,
        older_than_days: int = 90,
        deprecated_only: bool = True,
    ) -> None:
        """
        Remove stale or deprecated entries from the table.

        Args:
            older_than_days: Remove entries older than this many days.
            deprecated_only: If True, only remove entries marked as deprecated.
        """
        current_time = time.time()
        max_age_seconds = older_than_days * 24 * 60 * 60

        new_entries = []
        for entry in self.entries:
            status = entry.get("status", "verified")

            if status == "deprecated" and deprecated_only:
                continue

            created_at = entry.get("created_at", 0)
            if current_time - created_at > max_age_seconds:
                continue

            new_entries.append(entry)

        self.entries = new_entries
        self._rebuild_index()

    def get_stats(self) -> Dict[str, Any]:
        """
        Get statistics about the table.

        Returns:
            Dictionary with statistics.
        """
        if not self.entries:
            return {"total_entries": 0}

        macs_values = [e.get("macs", 0) for e in self.entries]
        ram_values = [e.get("ram_kb", 0) for e in self.entries]
        flash_values = [e.get("flash_kb", 0) for e in self.entries]
        latency_values = [e.get("latency_ms", 0) for e in self.entries]

        return {
            "total_entries": len(self.entries),
            "macs": {
                "min": min(macs_values),
                "max": max(macs_values),
                "avg": sum(macs_values) / len(macs_values),
            },
            "ram_kb": {
                "min": min(ram_values),
                "max": max(ram_values),
                "avg": sum(ram_values) / len(ram_values),
            },
            "flash_kb": {
                "min": min(flash_values),
                "max": max(flash_values),
                "avg": sum(flash_values) / len(flash_values),
            },
            "latency_ms": {
                "min": min(latency_values),
                "max": max(latency_values),
                "avg": sum(latency_values) / len(latency_values),
            },
            "metadata": self.metadata,
        }

    def find_best_for_constraints(
        self,
        max_macs: int,
        max_ram_kb: int,
        max_flash_kb: int,
    ) -> Optional[Dict[str, Any]]:
        """
        Find the best entry for given constraints (lower-level API).

        Args:
            max_macs: Maximum MACs.
            max_ram_kb: Maximum RAM in KB.
            max_flash_kb: Maximum Flash in KB.

        Returns:
            The best matching entry, or None if none found.
        """
        constraints = {
            "max_macs": max_macs,
            "max_ram": max_ram_kb * 1024,
            "max_flash": max_flash_kb * 1024,
        }
        return self.lookup(constraints)


